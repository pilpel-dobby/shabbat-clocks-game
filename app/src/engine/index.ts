export interface Clock {
  id: string;
  name: string;
  color: string; // CSS color or hex code
  teeth: boolean[]; // Array representing teeth state (true = ON, false = OFF)
  initialPosition: number; // Initial dial position (index in teeth array)
}

export interface ClockSimState {
  clockId: string;
  position: number;
  hasInputPower: boolean;
  hasOutputPower: boolean;
}

export interface SimulationStepResult {
  tick: number;
  outputPower: boolean;
  clocks: ClockSimState[];
}

export interface SimulationResult {
  timeline: boolean[];
  steps: SimulationStepResult[];
}

/**
 * Simulates a chain of Shabbat clocks over a given duration.
 * 
 * @param clocks Array of clocks in order (index 0 is connected to main power)
 * @param duration Number of ticks to simulate (e.g. 48 or 72)
 * @param mainPowerInput Initial power source state (default: true)
 */
export function simulate(
  clocks: Clock[],
  duration: number,
  mainPowerInput: boolean = true
): SimulationResult {
  const timeline: boolean[] = [];
  const steps: SimulationStepResult[] = [];

  // Track the current position index of each clock dial
  const currentPositions = clocks.map((c) => c.initialPosition);

  for (let tick = 0; tick < duration; tick++) {
    const clockStates: ClockSimState[] = [];
    let currentInput = mainPowerInput;

    // 1. Calculate states for all clocks at this tick
    for (let i = 0; i < clocks.length; i++) {
      const clock = clocks[i];
      const position = currentPositions[i];
      const teethCount = clock.teeth.length;
      
      // Wrap-around safety in case position is out of bounds
      const normalizedPosition = ((position % teethCount) + teethCount) % teethCount;
      const toothState = clock.teeth[normalizedPosition];
      
      const hasOutputPower = currentInput && toothState;

      clockStates.push({
        clockId: clock.id,
        position: normalizedPosition,
        hasInputPower: currentInput,
        hasOutputPower,
      });

      // The output of this clock becomes the input for the next clock
      currentInput = hasOutputPower;
    }

    // The output of the entire chain is the output of the last clock,
    // or the main power if no clocks are present.
    const outputPower = clocks.length > 0 ? currentInput : mainPowerInput;

    timeline.push(outputPower);
    steps.push({
      tick,
      outputPower,
      clocks: clockStates,
    });

    // 2. Advance positions of clocks that received input power during this tick
    for (let i = 0; i < clocks.length; i++) {
      const clock = clocks[i];
      const state = clockStates[i];
      
      if (state.hasInputPower) {
        currentPositions[i] = (state.position + 1) % clock.teeth.length;
      }
      // If no input power, the position remains the same (clock pauses)
    }
  }

  return {
    timeline,
    steps,
  };
}

/**
 * Checks if the actual timeline generated by the player matches the target timeline.
 */
export function evaluateSolution(actual: boolean[], target: boolean[]): boolean {
  if (actual.length !== target.length) return false;
  for (let i = 0; i < actual.length; i++) {
    if (actual[i] !== target[i]) return false;
  }
  return true;
}
